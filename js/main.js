function clampNumber(value, min, max) {
    return Math.min(max, Math.max(min, value));
}

function randomBetween(min, max) {
    return min + Math.random() * (max - min);
}

function getFloatingStageBounds(stage) {
    const rect = stage.getBoundingClientRect();
    return {
        width: Math.max(1, rect.width),
        height: Math.max(1, rect.height),
        safePad: Math.min(30, Math.max(12, rect.width * 0.022))
    };
}

function getFloatingMotionSettings(bounds = floatingStageBounds) {
    const touchSafe = (window.matchMedia && window.matchMedia("(hover: none), (pointer: coarse)").matches) || window.innerWidth <= 1024;
    const compact = Boolean(bounds && bounds.width < 640);
    const phone = Boolean(touchSafe && bounds && bounds.width < 520);
    return {
        touchSafe,
        compact,
        phone,
        speedMin: phone ? 18 : touchSafe ? (compact ? 42 : 82) : 120,
        speedMax: phone ? 44 : touchSafe ? (compact ? 78 : 140) : 210,
        radiusScale: phone ? 0.24 : touchSafe ? (compact ? 0.31 : 0.36) : 0.4,
        gap: phone ? -10 : touchSafe ? (compact ? 2 : 12) : 8,
        edgeBounce: phone ? 0.72 : touchSafe ? 0.86 : 1,
        turnForce: phone ? 4 : touchSafe ? (compact ? 10 : 18) : 28,
        turnMin: phone ? 1.8 : touchSafe ? 1.1 : 0.45,
        turnMax: phone ? 3.4 : touchSafe ? 2.3 : 1.25,
        separationStrength: phone ? 0.16 : touchSafe ? (compact ? 0.26 : 0.36) : 0.52,
        impulseScale: phone ? 0.18 : touchSafe ? 0.48 : 1.08,
        kickScale: phone ? 0.12 : touchSafe ? 0.28 : 0.52
    };
}

function getFloatingLimits(floater, bounds) {
    return {
        minX: bounds.safePad,
        minY: bounds.safePad,
        maxX: Math.max(bounds.safePad, bounds.width - floater.width - bounds.safePad),
        maxY: Math.max(bounds.safePad, bounds.height - floater.height - bounds.safePad)
    };
}

function setFloatingSpeed(floater, speed) {
    const angle = Math.atan2(floater.vy || 0, floater.vx || 1);
    floater.vx = Math.cos(angle) * speed;
    floater.vy = Math.sin(angle) * speed;
}

function keepFloatingSpeed(floater) {
    const settings = floatingMotionSettings;
    const speed = Math.hypot(floater.vx, floater.vy);
    if (!speed || speed < 1) {
        const angle = randomBetween(0, Math.PI * 2);
        const nextSpeed = randomBetween(settings.speedMin, settings.speedMax);
        floater.vx = Math.cos(angle) * nextSpeed;
        floater.vy = Math.sin(angle) * nextSpeed;
        return;
    }
    if (speed < settings.speedMin) setFloatingSpeed(floater, settings.speedMin);
    if (speed > settings.speedMax) setFloatingSpeed(floater, settings.speedMax);
}

function applyFloatingTransform(floater) {
    floater.element.style.transform = `translate3d(${floater.x.toFixed(2)}px, ${floater.y.toFixed(2)}px, 0) rotate(${floater.rotation.toFixed(2)}deg)`;
}

function bounceFloatingProject(floater) {
    const limits = getFloatingLimits(floater, floatingStageBounds);
    if (floater.x <= limits.minX) {
        floater.x = limits.minX;
        floater.vx = Math.abs(floater.vx) * floatingMotionSettings.edgeBounce;
    } else if (floater.x >= limits.maxX) {
        floater.x = limits.maxX;
        floater.vx = -Math.abs(floater.vx) * floatingMotionSettings.edgeBounce;
    }

    if (floater.y <= limits.minY) {
        floater.y = limits.minY;
        floater.vy = Math.abs(floater.vy) * floatingMotionSettings.edgeBounce;
    } else if (floater.y >= limits.maxY) {
        floater.y = limits.maxY;
        floater.vy = -Math.abs(floater.vy) * floatingMotionSettings.edgeBounce;
    }
}

function getFloatingRadius(floater) {
    return Math.max(floater.width, floater.height) * floatingMotionSettings.radiusScale;
}

function placeFloatingProject(index, count, width, height) {
    const bounds = floatingStageBounds;
    const lanes = [
        [0.12, 0.18],
        [0.68, 0.26],
        [0.34, 0.58],
        [0.82, 0.7],
        [0.48, 0.42]
    ];
    const lane = lanes[index % lanes.length];
    const maxX = Math.max(bounds.safePad, bounds.width - width - bounds.safePad);
    const maxY = Math.max(bounds.safePad, bounds.height - height - bounds.safePad);
    const softJitterX = floatingMotionSettings.phone ? 8 : 32;
    const softJitterY = floatingMotionSettings.phone ? 8 : 24;
    const x = clampNumber(bounds.safePad + (maxX - bounds.safePad) * lane[0] + randomBetween(-softJitterX, softJitterX), bounds.safePad, maxX);
    const y = clampNumber(bounds.safePad + (maxY - bounds.safePad) * lane[1] + randomBetween(-softJitterY, softJitterY), bounds.safePad, maxY);
    return { x, y };
}

function refreshFloatingProjectSizes() {
    const stage = document.querySelector(".floating-stage");
    if (!stage || !floaters.length) return;
    floatingStageBounds = getFloatingStageBounds(stage);
    floatingMotionSettings = getFloatingMotionSettings(floatingStageBounds);
    floaters.forEach((floater) => {
        const rect = floater.element.getBoundingClientRect();
        const minSize = floatingMotionSettings.phone ? 56 : 96;
        floater.width = Math.max(rect.width || 0, floater.width, minSize);
        floater.height = Math.max(rect.height || 0, floater.height, minSize);
        bounceFloatingProject(floater);
        keepFloatingSpeed(floater);
    });
}

function setupFloatingProjects() {
    const stage = document.querySelector(".floating-stage");
    const items = [...document.querySelectorAll(".floating-project")];
    if (!stage || !items.length) return;
    floatingStageBounds = getFloatingStageBounds(stage);
    floatingMotionSettings = getFloatingMotionSettings(floatingStageBounds);

    floaters = items.map((element, index) => {
        const rect = element.getBoundingClientRect();
        const minSize = floatingMotionSettings.phone ? 56 : 96;
        const width = Math.max(rect.width || 0, minSize);
        const height = Math.max(rect.height || 0, minSize);
        const position = placeFloatingProject(index, items.length, width, height);
        const angle = randomBetween(0, Math.PI * 2);
        const speed = randomBetween(floatingMotionSettings.speedMin, floatingMotionSettings.speedMax);
        const floater = {
            element,
            x: position.x,
            y: position.y,
            vx: Math.cos(angle) * speed,
            vy: Math.sin(angle) * speed,
            rotation: randomBetween(-8, 8),
            vr: randomBetween(-10, 10),
            turnTimer: randomBetween(0.55, 1.4),
            width,
            height
        };
        element.style.left = "0px";
        element.style.top = "0px";
        element.style.zIndex = String(20 + index);
        return floater;
    });

    separateFloatingProjects();
    floaters.forEach(applyFloatingTransform);
    lastFloatingTime = performance.now();
    if (floatingAnimationFrame) cancelAnimationFrame(floatingAnimationFrame);
    floatingAnimationFrame = requestAnimationFrame(animateFloatingProjects);
}

function animateFloatingProjects(timestamp = performance.now()) {
    if (!floatingStageBounds || !floatingMotionSettings || !floaters.length) return;
    const dt = Math.min(0.05, Math.max(0.001, (timestamp - lastFloatingTime) / 1000 || 1 / 60));
    lastFloatingTime = timestamp;

    floaters.forEach((floater) => {
        floater.turnTimer -= dt;
        if (floater.turnTimer <= 0) {
            const angle = randomBetween(0, Math.PI * 2);
            floater.vx += Math.cos(angle) * floatingMotionSettings.turnForce;
            floater.vy += Math.sin(angle) * floatingMotionSettings.turnForce;
            floater.vr += randomBetween(-4, 4);
            floater.turnTimer = randomBetween(floatingMotionSettings.turnMin, floatingMotionSettings.turnMax);
        }
        keepFloatingSpeed(floater);
        floater.x += floater.vx * dt;
        floater.y += floater.vy * dt;
        floater.rotation += floater.vr * dt;
        bounceFloatingProject(floater);
    });

    separateFloatingProjects();
    floaters.forEach(applyFloatingTransform);
    floatingAnimationFrame = requestAnimationFrame(animateFloatingProjects);
}

function separateFloatingProjects() {
    for (let i = 0; i < floaters.length; i += 1) {
        for (let j = i + 1; j < floaters.length; j += 1) {
            const a = floaters[i];
            const b = floaters[j];
            const ax = a.x + a.width / 2;
            const ay = a.y + a.height / 2;
            const bx = b.x + b.width / 2;
            const by = b.y + b.height / 2;
            let dx = bx - ax;
            let dy = by - ay;
            let distance = Math.hypot(dx, dy);
            if (distance < 0.001) {
                const angle = randomBetween(0, Math.PI * 2);
                dx = Math.cos(angle);
                dy = Math.sin(angle);
                distance = 1;
            }

            const minDistance = getFloatingRadius(a) + getFloatingRadius(b) + floatingMotionSettings.gap;
            if (distance >= minDistance) continue;

            const nx = dx / distance;
            const ny = dy / distance;
            const overlap = minDistance - distance;
            const separateBy = floatingMotionSettings.separationStrength;
            a.x -= nx * overlap * separateBy;
            a.y -= ny * overlap * separateBy;
            b.x += nx * overlap * separateBy;
            b.y += ny * overlap * separateBy;

            const relativeVelocity = (b.vx - a.vx) * nx + (b.vy - a.vy) * ny;
            if (relativeVelocity < 0) {
                const impulse = -relativeVelocity * floatingMotionSettings.impulseScale;
                a.vx -= nx * impulse;
                a.vy -= ny * impulse;
                b.vx += nx * impulse;
                b.vy += ny * impulse;
            } else {
                const kick = floatingMotionSettings.turnForce * floatingMotionSettings.kickScale;
                a.vx -= nx * kick;
                a.vy -= ny * kick;
                b.vx += nx * kick;
                b.vy += ny * kick;
            }

            bounceFloatingProject(a);
            bounceFloatingProject(b);
            keepFloatingSpeed(a);
            keepFloatingSpeed(b);
        }
    }
}

