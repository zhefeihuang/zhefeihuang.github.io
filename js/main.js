function protectMediaElements(root = document) {
    root.querySelectorAll("img, video, audio, canvas, svg").forEach((node) => {
        node.setAttribute("draggable", "false");
        node.setAttribute("data-protected-media", "true");
        node.addEventListener("contextmenu", blockProtectedAction);
        node.addEventListener("dragstart", blockProtectedAction);
        if (node.tagName === "VIDEO" || node.tagName === "AUDIO") {
            node.setAttribute("controlsList", "nodownload noplaybackrate noremoteplayback");
            node.setAttribute("disablePictureInPicture", "");
            node.setAttribute("disableRemotePlayback", "");
        }
    });
}

function blockProtectedAction(event) {
    const allowEmailCopy = event.target?.closest?.(".copy-email");
    if (allowEmailCopy) return;
    event.preventDefault();
    event.stopPropagation();
    triggerProtectionVeil();
}

function triggerProtectionVeil(duration = 1150) {
    document.body.classList.add("content-protection-active");
    window.clearTimeout(triggerProtectionVeil.timer);
    triggerProtectionVeil.timer = window.setTimeout(() => {
        document.body.classList.remove("content-protection-active");
    }, duration);
}

function installContentProtection() {
    protectMediaElements(document);

    ["contextmenu", "dragstart", "drop", "copy", "cut", "paste", "selectstart"].forEach((type) => {
        document.addEventListener(type, blockProtectedAction, { capture: true });
    });

    document.addEventListener("keydown", (event) => {
        const key = event.key.toLowerCase();
        const protectedShortcut =
            event.key === "PrintScreen" ||
            event.key === "F12" ||
            ((event.ctrlKey || event.metaKey) && ["s", "p", "u", "c", "x", "a"].includes(key)) ||
            ((event.ctrlKey || event.metaKey) && event.shiftKey && ["i", "j", "c", "s"].includes(key));

        if (!protectedShortcut) return;
        blockProtectedAction(event);
        if (event.key === "PrintScreen" && navigator.clipboard?.writeText) {
            navigator.clipboard.writeText("").catch(() => {});
        }
    }, { capture: true });

    window.addEventListener("beforeprint", () => {
        document.body.classList.add("content-protection-active");
    });

    window.addEventListener("afterprint", () => {
        document.body.classList.remove("content-protection-active");
    });
}

