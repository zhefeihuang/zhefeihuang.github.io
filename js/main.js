window.addEventListener("pointermove", (event) => {
    mouseX = event.clientX;
    mouseY = event.clientY;
    const trailZone = event.target.closest("[data-trail], .project-room");
    const trailGap = event.pointerType === "touch" || event.pointerType === "pen" ? 72 : 132;
    if (trailZone && distance(mouseX, mouseY, lastTrailX, lastTrailY) > trailGap) {
        makeTrail(mouseX, mouseY);
        lastTrailX = mouseX;
        lastTrailY = mouseY;
    }
});

window.addEventListener("pointerdown", (event) => {
    mouseX = event.clientX;
    mouseY = event.clientY;
    const touchLike = event.pointerType === "touch" || event.pointerType === "pen";
    const projectButton = event.target.closest("[data-project]");
    if (touchLike && projectButton?.dataset.cursor) setCursor(projectButton.dataset.cursor);
    if (touchLike && event.target.closest("[data-trail], .project-room, [data-project]")) {
        makeTrail(mouseX, mouseY);
        window.setTimeout(() => makeTrail(mouseX + 18, mouseY + 10), 65);
        window.setTimeout(() => makeTrail(mouseX - 14, mouseY + 22), 125);
    }
});

