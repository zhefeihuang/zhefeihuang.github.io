function setupProjectSound(project) {
    stopProjectSound();
    if (!project.audio) {
        soundControl.hidden = true;
        return;
    }
    soundControl.hidden = false;
    currentAudioStart = Number(project.audioStart || 0);
    bgAudio.loop = currentAudioStart <= 0;
    bgAudio.src = project.audio;
    bgAudio.volume = Number(soundVolume.value);
    if (currentAudioStart > 0) {
        const jumpToSound = () => {
            try {
                const safeStart = Number.isFinite(bgAudio.duration)
                    ? Math.min(currentAudioStart, Math.max(0, bgAudio.duration - 0.5))
                    : currentAudioStart;
                bgAudio.currentTime = safeStart;
            } catch {
                // Some browsers only allow seeking after metadata has loaded.
            }
        };
        bgAudio.addEventListener("loadedmetadata", jumpToSound, { once: true });
        bgAudio.addEventListener("play", jumpToSound, { once: true });
        jumpToSound();
    }
    updateVolumeVisual();
    soundReady = true;
    soundToggle.dataset.soundText = "on";
    updateSoundText();
    bgAudio.play().catch(() => {
        soundToggle.dataset.soundText = "play";
        updateSoundText();
    });
}

function stopProjectSound() {
    bgAudio.pause();
    bgAudio.removeAttribute("src");
    bgAudio.load();
    currentAudioStart = 0;
    bgAudio.loop = true;
    soundReady = false;
    soundControl.hidden = true;
}

function updateSoundText() {
    const mode = soundToggle.dataset.soundText || "on";
    if (mode === "off") soundToggle.textContent = t("soundOff");
    else if (mode === "play") soundToggle.textContent = t("playSound");
    else soundToggle.textContent = t("soundOn");
}

function updateVolumeVisual() {
    const percent = Math.max(0, Math.min(100, Math.round(Number(soundVolume.value) * 100)));
    soundVolume.style.setProperty("--volume-pct", `${percent}%`);
}

function toggleSound() {
    if (!soundReady || !bgAudio.src) return;
    if (bgAudio.paused) {
        bgAudio.play().then(() => {
            soundToggle.dataset.soundText = "on";
            updateSoundText();
        }).catch(() => {
            soundToggle.dataset.soundText = "play";
            updateSoundText();
        });
    } else {
        bgAudio.pause();
        soundToggle.dataset.soundText = "off";
        updateSoundText();
    }
}

