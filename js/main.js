function escapeHtml(value) {
    return String(value)
        .replace(/&/g, "&amp;")
        .replace(/</g, "&lt;")
        .replace(/>/g, "&gt;")
        .replace(/"/g, "&quot;")
        .replace(/'/g, "&#039;");
}

function protectChineseTail(value) {
    const text = String(value || "");
    if (currentLang !== "zh" || text.length < 8) return escapeHtml(text);
    const match = text.match(/([\u4e00-\u9fffA-Za-z0-9，。；：！？、（）《》“”‘’]{2,7}[，。；：！？、）]?)[\s]*$/u);
    if (!match) return escapeHtml(text);
    const tail = match[1];
    const head = text.slice(0, text.length - tail.length);
    return `${escapeHtml(head)}<span class="keep-tail">${escapeHtml(tail)}</span>`;
}

function setFormattedText(node, value) {
    node.innerHTML = protectChineseTail(value);
}

